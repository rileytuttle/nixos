#!/usr/bin/env python3
"""
Install the system-level half of bt-kb-emulator on a host where nix is just
a package manager (Ubuntu, Fedora, Arch...) rather than the whole OS.

home-manager cannot do this part. Two of the three things needed here are
root-owned system state, not user state:

- `bluetoothd --noplugin=input`. The HID *host* plugin binds L2CAP PSM
  0x11/0x13 and claims the HID UUID, which the HID *device* role needs; it
  has to be turned off in the system bluetooth.service.
- a system systemd unit for hid_server.py, which needs real root for raw
  AF_BLUETOOTH sockets, so a `systemd --user` service cannot host it.

So this script writes those two units and reloads systemd, asking for sudo.
It only ever creates files under /etc/systemd/system that it marks as its
own, and never edits a file the distro owns -- so --uninstall is exact.

    bt-kb-setup              install, then start everything
    bt-kb-setup --status     what is installed and running
    bt-kb-setup --uninstall  remove both units, restore bluetoothd
"""
import argparse
import os
import shlex
import shutil
import subprocess
import sys

MARKER = "# Generated by bt-kb-setup (bt-kb-emulator). Do not edit."

UNIT_DIR = "/etc/systemd/system"
SERVICE_NAME = "bt-kb-hid-server.service"
SERVICE_PATH = os.path.join(UNIT_DIR, SERVICE_NAME)
# 90- so it sorts after whatever the distro ships.
BT_DROPIN_DIR = os.path.join(UNIT_DIR, "bluetooth.service.d")
BT_DROPIN_PATH = os.path.join(BT_DROPIN_DIR, "90-bt-kb-emulator.conf")

# $out of the package this script was installed from:
#   $out/share/bt-kb-emulator/setup_system.py -> $out
# Checked before anything else, including the sudo re-exec: on NixOS this
# script must refuse without so much as asking for a password.
IS_NIXOS = os.path.exists("/etc/NIXOS")

NIXOS_MESSAGE = (
    "this is NixOS -- use the NixOS module instead, which declares all of\n"
    "this in the system config:\n"
    "    imports = [ .../bt-kb-emulator/module.nix ];\n"
    "Installing imperative units here would fight with it."
)

PREFIX = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SERVER_BIN = os.path.join(PREFIX, "bin", "bt-kb-hid-server")


def run(argv, check=True, quiet=False):
    if not quiet:
        print("  $ " + " ".join(shlex.quote(a) for a in argv))
    return subprocess.run(argv, check=check, capture_output=True, text=True)


def systemctl(*args, check=True, quiet=False):
    return run(["systemctl", *args], check=check, quiet=quiet)


def die(msg):
    sys.exit(f"bt-kb-setup: {msg}")


def is_ours(path):
    """True only for a file this script wrote.

    Existence is not enough: on NixOS /etc/systemd/system/bt-kb-hid-server.service
    is a symlink the NixOS module generated, and calling that "installed by
    bt-kb-setup" led to telling the user to re-run a command that refuses to
    run there at all.
    """
    if not os.path.exists(path):
        return False
    try:
        with open(path) as f:
            return MARKER in f.read()
    except OSError:
        return False


def preflight():
    if not shutil.which("systemctl") or not os.path.isdir("/run/systemd/system"):
        die("no running systemd found; this script only knows how to set up systemd units")
    if not os.path.exists(SERVER_BIN):
        die(f"{SERVER_BIN} is missing -- is this script running from the nix package?")
    probe = systemctl("list-unit-files", "bluetooth.service", check=False, quiet=True)
    if "bluetooth.service" not in probe.stdout:
        die("no bluetooth.service on this host -- install bluez (e.g. apt install bluez) first")


def bluetoothd_argv():
    """The argv systemd currently uses for bluetoothd."""
    out = systemctl("show", "-p", "ExecStart", "--value", "bluetooth.service", quiet=True).stdout
    # Format: { path=/usr/libexec/bluetooth/bluetoothd ; argv[]=/usr/... -f x ; ignore_errors=no ; ... }
    marker = "argv[]="
    start = out.find(marker)
    if start == -1:
        die(f"could not parse bluetooth.service ExecStart:\n{out.strip()}")
    rest = out[start + len(marker):]
    end = rest.find(" ; ")
    argv_str = rest if end == -1 else rest[:end]
    try:
        argv = shlex.split(argv_str)
    except ValueError:
        argv = argv_str.split()
    if not argv:
        die(f"bluetooth.service has an empty ExecStart:\n{out.strip()}")
    return argv


def with_input_plugin_disabled(argv):
    """argv + --noplugin=input, merged into any --noplugin the host already has.

    Rewriting rather than blindly appending: a second --noplugin= would
    override the first, silently re-enabling whatever the distro disabled.
    """
    kept = [argv[0]]
    disabled = set()
    i = 1
    while i < len(argv):
        arg = argv[i]
        if arg.startswith("--noplugin="):
            disabled.update(filter(None, arg.split("=", 1)[1].split(",")))
        elif arg == "--noplugin" or arg == "-P":
            if i + 1 < len(argv):
                disabled.update(filter(None, argv[i + 1].split(",")))
                i += 1
        elif arg.startswith("-P"):
            disabled.update(filter(None, arg[2:].split(",")))
        else:
            kept.append(arg)
        i += 1
    disabled.add("input")
    kept.append("--noplugin=" + ",".join(sorted(disabled)))
    return kept


def write_file(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    existing = None
    if os.path.exists(path):
        with open(path) as f:
            existing = f.read()
        if existing == content:
            print(f"  unchanged {path}")
            return False
        if MARKER not in existing:
            die(
                f"{path} exists and was not written by bt-kb-setup.\n"
                "Refusing to overwrite someone else's file; move it aside first."
            )
    with open(path, "w") as f:
        f.write(content)
    print(f"  {'rewrote' if existing else 'wrote'} {path}")
    return True


def remove_file(path):
    if not os.path.exists(path):
        return False
    with open(path) as f:
        if MARKER not in f.read():
            print(f"  skipping {path} (not ours)")
            return False
    os.unlink(path)
    print(f"  removed {path}")
    return True


def install():
    preflight()
    argv = bluetoothd_argv()
    print(f"\nbluetoothd currently starts as:\n  {' '.join(argv)}")
    new_argv = with_input_plugin_disabled(argv)

    print("\nwriting units:")
    dropin = f"""{MARKER}
#
# bluetoothd's `input` plugin is the HID *host* role: it binds L2CAP PSM
# 0x11/0x13 and claims the HID UUID as soon as it loads, which is exactly
# what the HID *device* role needs. Note this costs Bluetooth keyboard and
# mouse support on this machine for as long as it is in place.
#
# `DisablePlugins` in /etc/bluetooth/main.conf does NOT do this -- it is not
# a main.conf key in BlueZ 5.x and is silently ignored. Only the command
# line flag works, hence this drop-in.
[Service]
ExecStart=
ExecStart={" ".join(shlex.quote(a) for a in new_argv)}
"""
    write_file(BT_DROPIN_PATH, dropin)

    service = f"""{MARKER}
#
# Deliberately not enabled: the pairing agent auto-accepts anything in range
# while the adapter is discoverable, so this should be running only while you
# are actually pairing. Start it by hand, then run bt-kb-keygrab as yourself.
#
# ExecStart points into /nix/store. Re-run bt-kb-setup after a home-manager
# update, or this keeps starting the old build (bt-kb-setup --status checks).
[Unit]
Description=Bluetooth HID-device keyboard emulator server
After=bluetooth.service dbus.service
Requires=bluetooth.service

[Service]
Type=simple
ExecStart={SERVER_BIN}
Restart=on-failure
RestartSec=2
# Exit 78 is EX_CONFIG: the environment is wrong (input plugin still loaded,
# not root, PSM taken). Retrying cannot fix that, it just spins.
RestartPreventExitStatus=78
"""
    write_file(SERVICE_PATH, service)

    print("\nreloading and restarting:")
    systemctl("daemon-reload")
    # bluetoothd must be restarted for the new argv to take effect; the
    # drop-in on disk changes nothing about the already-running process.
    systemctl("restart", "bluetooth.service")

    # Class of Device, so the phone shows a keyboard and does not filter us
    # out. Best effort: btmgmt takes DECIMAL major/minor (it uses atoi), so
    # this is `5 64`, not `0x05 0x40`. bluetoothd may reassert its own class,
    # in which case use the main.conf route printed below.
    if shutil.which("btmgmt"):
        res = run(["btmgmt", "--index", "0", "class", "5", "64"], check=False)
        if res.returncode != 0:
            print("  (btmgmt class failed; see the note below)")
    else:
        print("  (no btmgmt found; see the note below)")

    systemctl("restart", SERVICE_NAME)
    print()
    status(brief=True)
    print(
        "\nNext:\n"
        "  1. journalctl -u bt-kb-hid-server -f        watch the link\n"
        "  2. pair the phone with this machine's keyboard device\n"
        "  3. bt-kb-send --status                      confirm the phone is connected\n"
        "  4. bt-kb-send hello                         type without the GUI\n"
        "  5. bt-kb-keygrab                            the capture window\n"
        "\nIf the phone does not list us as a keyboard, add this under [General]\n"
        "in /etc/bluetooth/main.conf and restart bluetooth:\n"
        "  Class = 0x000540\n"
    )


def uninstall():
    print("removing units:")
    systemctl("stop", SERVICE_NAME, check=False)
    removed = remove_file(SERVICE_PATH)
    removed |= remove_file(BT_DROPIN_PATH)
    if not removed:
        print("  nothing to remove")
        return
    systemctl("daemon-reload")
    # Deleting our drop-in restores the distro's ExecStart, because the
    # drop-in only ever reset-and-replaced it; nothing else to put back.
    systemctl("restart", "bluetooth.service")
    print("\nbluetoothd is back to its packaged command line "
          "(Bluetooth keyboards/mice work again).")


def status(brief=False):
    if IS_NIXOS:
        print("  managed by the NixOS module (module.nix), not by bt-kb-setup")
    else:
        for label, path in (("service unit", SERVICE_PATH), ("bluetooth drop-in", BT_DROPIN_PATH)):
            print(f"  {label:<18} {'installed' if is_ours(path) else 'not installed'}  {path}")

    running = systemctl("show", "-p", "ExecStart", "--value", "bluetooth.service", quiet=True).stdout
    plugin_off = "--noplugin=" in running and "input" in running.split("--noplugin=", 1)[1].split()[0]
    print(f"  input plugin       {'disabled' if plugin_off else 'STILL ENABLED'}")
    for unit in ("bluetooth.service", SERVICE_NAME):
        state = systemctl("is-active", unit, check=False, quiet=True).stdout.strip()
        print(f"  {unit:<18} {state}")

    # Only meaningful for a unit we wrote; the NixOS one is updated by a
    # rebuild and is never "stale" in this sense.
    if is_ours(SERVICE_PATH):
        with open(SERVICE_PATH) as f:
            unit_text = f.read()
        if SERVER_BIN not in unit_text:
            wants = [l for l in unit_text.splitlines() if l.startswith("ExecStart=")]
            print(
                f"\n  STALE: the installed unit does not point at this build.\n"
                f"    unit wants: {wants}\n"
                f"    this build: {SERVER_BIN}\n"
                "  Re-run bt-kb-setup."
            )
    if not brief:
        print("\n  pgrep -af bluetoothd:")
        res = run(["pgrep", "-af", "bluetoothd"], check=False, quiet=True)
        for line in res.stdout.strip().splitlines():
            print(f"    {line}")


def main():
    ap = argparse.ArgumentParser(
        description="Install the root-owned half of bt-kb-emulator on a non-NixOS host.",
        epilog="Re-run after a home-manager update: the unit pins a /nix/store path.",
    )
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--uninstall", action="store_true", help="remove the units and restore bluetoothd")
    g.add_argument("--status", action="store_true", help="show what is installed and running")
    args = ap.parse_args()

    # Before the sudo re-exec, so NixOS gets a straight refusal rather than
    # a password prompt followed by one.
    if IS_NIXOS and not args.status:
        die(NIXOS_MESSAGE)

    if args.status:
        # Read-only; no reason to ask for a password.
        print("bt-kb-emulator system state:")
        status()
        return 0

    if os.geteuid() != 0:
        # Re-exec under sudo rather than telling the user to retype it. The
        # absolute script path matters: sudo resets PATH, and $0 may be
        # relative. sys.executable is the nix python this was wrapped with.
        print("bt-kb-setup needs root to write system units; re-running under sudo...")
        argv = ["sudo", "--", sys.executable, os.path.abspath(__file__)] + sys.argv[1:]
        try:
            os.execvp("sudo", argv)
        except OSError as exc:
            die(f"could not re-exec under sudo: {exc}")

    try:
        if args.uninstall:
            uninstall()
        else:
            install()
    except subprocess.CalledProcessError as exc:
        die(f"{' '.join(exc.cmd)} failed ({exc.returncode}):\n{exc.stderr or exc.stdout}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
